import { useCallback, useEffect, useRef, useState } from 'react';
import Composer from '../ui/Composer';
import { CanvasElement, PendingConfirm } from '../useRaven';

interface DesignStageProps {
    canvasElements: CanvasElement[];
    busy: boolean;
    cancelling: boolean;
    statusText: string | null;
    error: string | null;
    connected: boolean;
    pendingConfirm: PendingConfirm | null;
    onSend: (text: string) => void;
    onCancel: () => void;
    onDismissError: () => void;
    editCanvasElement: (elementId: string, patch: Record<string, unknown>) => void;
    deleteCanvasElement: (elementId: string) => void;
    groupCanvasElements: (elementIds: string[]) => void;
    ungroupCanvasElement: (groupId: string) => void;
    restoreCanvasElement: (element: CanvasElement) => void;
}

// ---------------------------------------------------------------------------
// Canvas geometry helpers. Every element's own geometry (points/d/children)
// is server-authoritative -- generated by raven/design.py and never computed
// here -- these helpers only ever read it to render/hit-test/position UI
// chrome (selection outlines, resize/rotate handles), never to derive a
// shape's actual shown geometry.
// ---------------------------------------------------------------------------

const DEFAULT_VIEWBOX = { x: -500, y: -350, w: 1000, h: 700 };
const MIN_ZOOM_W = 100;   // most zoomed-in: viewBox width, canvas units
const MAX_ZOOM_W = 4000;  // most zoomed-out

type ViewBox = { x: number; y: number; w: number; h: number };
type Point = { x: number; y: number };

function pointsToAttr(points: [number, number][] | undefined): string {
    return (points ?? []).map(([x, y]) => `${x},${y}`).join(' ');
}

// A generator's own "primary size" param, used by the resize handle to
// regenerate exact geometry via a param change rather than an approximate
// visual stretch -- only for shapes with ONE clear size knob. Anything else
// (groups, bezier curves, grids) resizes via the element's own `scale`
// field instead (see the resize pointer handler below).
function primarySizeParam(el: CanvasElement): string | null {
    switch (el.generator) {
        case 'regular_polygon': return 'radius';
        case 'golden_rectangle': return 'width';
        case 'golden_spiral': return 'size';
        case 'lissajous_curve': return 'amplitude';
        default: return null;
    }
}

function localBBox(ref: SVGGraphicsElement | null): { x: number; y: number; w: number; h: number } | null {
    if (!ref) return null;
    try {
        const box = ref.getBBox();
        if (!isFinite(box.width) || !isFinite(box.height)) return null;
        return { x: box.x, y: box.y, w: box.width, h: box.height };
    } catch {
        return null; // an unmounted/hidden node can throw -- selection just skips it that frame
    }
}

function screenToCanvas(svg: SVGSVGElement, viewBox: ViewBox, clientX: number, clientY: number): Point {
    const rect = svg.getBoundingClientRect();
    const x = viewBox.x + ((clientX - rect.left) / rect.width) * viewBox.w;
    const y = viewBox.y + ((clientY - rect.top) / rect.height) * viewBox.h;
    return { x, y };
}

// ---------------------------------------------------------------------------
// Undo/redo: a plain stack of already-applied-vs-to-apply callback pairs.
// Move/resize/rotate/recolor/reparametrize/group/ungroup/delete each push
// one entry when committed; Ctrl+Z/Ctrl+Shift+Z just replay the matching
// side using the SAME editCanvasElement/deleteCanvasElement/etc. calls a
// live user action would make, so the server stays the single source of
// truth throughout (undo is never a purely-local visual revert).
// ---------------------------------------------------------------------------

type UndoEntry = { undo: () => void; redo: () => void };

function useUndoStack() {
    const undoStack = useRef<UndoEntry[]>([]);
    const redoStack = useRef<UndoEntry[]>([]);

    const push = useCallback((entry: UndoEntry) => {
        undoStack.current.push(entry);
        redoStack.current = []; // a fresh action invalidates any redo history
    }, []);

    const undo = useCallback(() => {
        const entry = undoStack.current.pop();
        if (!entry) return;
        entry.undo();
        redoStack.current.push(entry);
    }, []);

    const redo = useCallback(() => {
        const entry = redoStack.current.pop();
        if (!entry) return;
        entry.redo();
        undoStack.current.push(entry);
    }, []);

    return { push, undo, redo };
}

// ---------------------------------------------------------------------------
// One element's rendered geometry (recursive -- a group renders its children
// inside its own transform, exactly the composition raven/design.py's
// ungroup_elements bakes in explicitly when a group is later taken apart).
// ---------------------------------------------------------------------------

function ShapeGeometry({ el }: { el: CanvasElement }) {
    if (el.type === 'group') {
        return (
            <>
                {(el.children ?? []).map((child) => (
                    <g key={child.id} transform={`translate(${child.x} ${child.y}) rotate(${child.rotation}) scale(${child.scale ?? 1})`}>
                        <ShapeGeometry el={child} />
                    </g>
                ))}
            </>
        );
    }
    if (el.type === 'path') {
        return <path d={el.d} fill={el.fill} stroke={el.stroke} strokeWidth={el.stroke_width} />;
    }
    // polygon and star both render as a closed <polygon> -- the only
    // difference between them is how design.py computed the vertices.
    return <polygon points={pointsToAttr(el.points)} fill={el.fill} stroke={el.stroke} strokeWidth={el.stroke_width} />;
}

const HANDLE_SIZE = 7;
const ROTATE_HANDLE_OFFSET = 24;

function SelectionChrome({ bbox }: { bbox: { x: number; y: number; w: number; h: number } }) {
    const corners: [number, number][] = [
        [bbox.x, bbox.y], [bbox.x + bbox.w, bbox.y],
        [bbox.x + bbox.w, bbox.y + bbox.h], [bbox.x, bbox.y + bbox.h],
    ];
    return (
        <>
            <rect
                x={bbox.x} y={bbox.y} width={bbox.w} height={bbox.h}
                fill="none" stroke="var(--color-ink)" strokeWidth={1} strokeDasharray="4 3"
                pointerEvents="none"
            />
            <line
                x1={bbox.x + bbox.w / 2} y1={bbox.y} x2={bbox.x + bbox.w / 2} y2={bbox.y - ROTATE_HANDLE_OFFSET}
                stroke="var(--color-ink)" strokeWidth={1} pointerEvents="none"
            />
            <circle
                data-handle="rotate" cx={bbox.x + bbox.w / 2} cy={bbox.y - ROTATE_HANDLE_OFFSET} r={5}
                fill="var(--color-strong)" stroke="var(--color-ink)" className="cursor-alias"
            />
            {corners.map(([cx, cy], i) => (
                <rect
                    key={i} data-handle="resize" data-corner={i}
                    x={cx - HANDLE_SIZE / 2} y={cy - HANDLE_SIZE / 2} width={HANDLE_SIZE} height={HANDLE_SIZE}
                    fill="var(--color-strong)" stroke="var(--color-ink)" className="cursor-nwse-resize"
                />
            ))}
        </>
    );
}

// ---------------------------------------------------------------------------

const DesignStage = ({
    canvasElements, busy, cancelling, statusText, error, connected, pendingConfirm,
    onSend, onCancel, onDismissError,
    editCanvasElement, deleteCanvasElement, groupCanvasElements, ungroupCanvasElement, restoreCanvasElement,
}: DesignStageProps) => {
    const svgRef = useRef<SVGSVGElement>(null);
    const shapeRefs = useRef(new Map<string, SVGGElement>());
    const [viewBox, setViewBox] = useState<ViewBox>(DEFAULT_VIEWBOX);
    // The wheel listener below is attached once (not re-attached every pan/
    // zoom), so it needs a ref to read the CURRENT viewBox rather than a
    // stale one captured when the listener was first attached.
    const viewBoxRef = useRef(viewBox);
    useEffect(() => { viewBoxRef.current = viewBox; }, [viewBox]);
    // Figma's own toolbar toggle between the select/move cursor (V) and the
    // hand/pan tool (H) -- same role spacePressed already had (hold Space to
    // pan temporarily), just also selectable as a sticky tool so panning
    // doesn't require holding a key down the whole time.
    const [tool, setTool] = useState<'select' | 'hand'>('select');
    const [selection, setSelection] = useState<Set<string>>(new Set());
    // Live-drag visual overrides, keyed by element id -- applied on TOP of
    // the server's own canvasElements while a drag/resize/rotate is in
    // progress, so the canvas re-renders every pointermove without sending
    // a websocket message per frame; a single edit commits on release.
    const [liveOverrides, setLiveOverrides] = useState<Record<string, Partial<CanvasElement>>>({});
    const [marquee, setMarquee] = useState<{ x0: number; y0: number; x1: number; y1: number } | null>(null);
    const dragRef = useRef<null | {
        kind: 'move' | 'resize' | 'rotate';
        pointerId: number;
        startCanvas: Point;
        // move: each selected element's starting x/y; resize: the one
        // element's starting param/scale + its local bbox; rotate: the
        // element's starting rotation + the angle from its center to the
        // pointer at drag start.
        elements: Record<string, { x: number; y: number; rotation: number; scale: number; paramValue?: number }>;
        elementId?: string;
        startBBox?: { w: number; h: number };
        startAngle?: number;
    }>(null);
    const { push: pushUndo, undo, redo } = useUndoStack();

    const topLevel = canvasElements; // groups nest their own children -- this list is already "what's selectable"

    const displayElement = useCallback(
        (el: CanvasElement): CanvasElement => ({ ...el, ...liveOverrides[el.id] }),
        [liveOverrides],
    );

    // -- selection / marquee --------------------------------------------------

    const clearSelection = () => setSelection(new Set());

    const selectOnly = (id: string) => setSelection(new Set([id]));

    const toggleSelect = (id: string) =>
        setSelection((prev) => {
            const next = new Set(prev);
            if (next.has(id)) next.delete(id); else next.add(id);
            return next;
        });

    // -- pan / zoom -------------------------------------------------------------

    const spacePressed = useRef(false);
    useEffect(() => {
        const down = (e: KeyboardEvent) => { if (e.code === 'Space') spacePressed.current = true; };
        const up = (e: KeyboardEvent) => { if (e.code === 'Space') spacePressed.current = false; };
        window.addEventListener('keydown', down);
        window.addEventListener('keyup', up);
        return () => { window.removeEventListener('keydown', down); window.removeEventListener('keyup', up); };
    }, []);

    // Shared by the wheel handler AND the toolbar's +/- buttons, so scroll-
    // zoom and click-zoom can never drift into different math. `center`
    // defaults to the viewport's own center (toolbar buttons have no
    // pointer position to zoom around); the wheel handler passes the real
    // cursor position instead, so the shape under it stays under it.
    const zoomBy = useCallback((factor: number, center?: Point) => {
        setViewBox((vb) => {
            const newW = Math.min(MAX_ZOOM_W, Math.max(MIN_ZOOM_W, vb.w * factor));
            const newH = newW * (vb.h / vb.w);
            const pivot = center ?? { x: vb.x + vb.w / 2, y: vb.y + vb.h / 2 };
            const ratio = newW / vb.w;
            return {
                x: pivot.x - (pivot.x - vb.x) * ratio,
                y: pivot.y - (pivot.y - vb.y) * ratio,
                w: newW, h: newH,
            };
        });
    }, []);

    const zoomToFit = useCallback(() => {
        if (topLevel.length === 0) {
            setViewBox(DEFAULT_VIEWBOX);
            return;
        }
        // Centers-of-elements with a fixed margin -- same "simple and
        // predictable over pixel-perfect" scoping the marquee hit-test
        // already uses, rather than measuring every shape's real bbox.
        const margin = 150;
        const xs = topLevel.map((el) => el.x);
        const ys = topLevel.map((el) => el.y);
        const minX = Math.min(...xs) - margin, maxX = Math.max(...xs) + margin;
        const minY = Math.min(...ys) - margin, maxY = Math.max(...ys) + margin;
        const w = Math.max(MIN_ZOOM_W, maxX - minX);
        const h = w * (DEFAULT_VIEWBOX.h / DEFAULT_VIEWBOX.w);
        setViewBox({ x: (minX + maxX) / 2 - w / 2, y: (minY + maxY) / 2 - h / 2, w, h });
    }, [topLevel]);

    // A native (non-passive) listener, not JSX's onWheel -- React attaches
    // wheel handlers as passive by default, which silently no-ops
    // preventDefault() (confirmed live: the browser logs "Unable to
    // preventDefault inside passive event listener invocation" and the
    // page scrolls along with the zoom). {passive: false} is required to
    // actually stop that.
    useEffect(() => {
        const svg = svgRef.current;
        if (!svg) return;
        const handler = (e: WheelEvent) => {
            e.preventDefault();
            const factor = e.deltaY > 0 ? 1.1 : 1 / 1.1;
            zoomBy(factor, screenToCanvas(svg, viewBoxRef.current, e.clientX, e.clientY));
        };
        svg.addEventListener('wheel', handler, { passive: false });
        return () => svg.removeEventListener('wheel', handler);
    }, [zoomBy]);

    // -- pointer interaction: marquee-select, move, resize, rotate --------------

    const onShapePointerDown = (e: React.PointerEvent, el: CanvasElement) => {
        if (busy) return;
        // Hand tool disables shape interaction entirely (Figma's own
        // behavior) -- let the event bubble up to the canvas's own
        // pointerdown/move handlers so panning works even when the pointer
        // starts on top of a shape, not just on empty canvas.
        if (tool === 'hand') return;
        const target = e.target as SVGElement;
        const handle = target.getAttribute('data-handle');
        e.stopPropagation();
        (e.target as Element).setPointerCapture(e.pointerId);
        const svg = svgRef.current;
        if (!svg) return;
        const startCanvas = screenToCanvas(svg, viewBox, e.clientX, e.clientY);

        if (handle === 'rotate') {
            const startAngle = Math.atan2(startCanvas.y - el.y, startCanvas.x - el.x) * (180 / Math.PI);
            dragRef.current = {
                kind: 'rotate', pointerId: e.pointerId, startCanvas,
                elements: { [el.id]: { x: el.x, y: el.y, rotation: el.rotation, scale: el.scale ?? 1 } },
                elementId: el.id, startAngle,
            };
            return;
        }
        if (handle === 'resize') {
            const bbox = localBBox(shapeRefs.current.get(el.id) ?? null);
            dragRef.current = {
                kind: 'resize', pointerId: e.pointerId, startCanvas,
                elements: {
                    [el.id]: {
                        x: el.x, y: el.y, rotation: el.rotation, scale: el.scale ?? 1,
                        paramValue: primarySizeParam(el) ? Number(el.params[primarySizeParam(el) as string]) : undefined,
                    },
                },
                elementId: el.id, startBBox: bbox ? { w: bbox.w, h: bbox.h } : { w: 1, h: 1 },
            };
            return;
        }
        // Plain click on the shape body: select (or extend selection with
        // shift), then arm a move drag for the WHOLE current selection.
        setSelection((prev) => {
            const next = e.shiftKey ? new Set(prev) : new Set<string>();
            if (e.shiftKey && prev.has(el.id)) next.delete(el.id); else next.add(el.id);
            const elements: Record<string, { x: number; y: number; rotation: number; scale: number }> = {};
            for (const id of next) {
                const found = topLevel.find((c) => c.id === id);
                if (found) elements[id] = { x: found.x, y: found.y, rotation: found.rotation, scale: found.scale ?? 1 };
            }
            dragRef.current = { kind: 'move', pointerId: e.pointerId, startCanvas, elements };
            return next;
        });
    };

    const onCanvasPointerDown = (e: React.PointerEvent<SVGSVGElement>) => {
        if (busy || spacePressed.current || tool === 'hand') return;
        const svg = svgRef.current;
        if (!svg) return;
        const p = screenToCanvas(svg, viewBox, e.clientX, e.clientY);
        clearSelection();
        setMarquee({ x0: p.x, y0: p.y, x1: p.x, y1: p.y });
        svg.setPointerCapture(e.pointerId);
    };

    const onCanvasPointerMove = (e: React.PointerEvent<SVGSVGElement>) => {
        const svg = svgRef.current;
        if (!svg) return;
        if ((spacePressed.current || tool === 'hand') && e.buttons === 1) {
            setViewBox((vb) => ({
                ...vb,
                x: vb.x - (e.movementX / svg.getBoundingClientRect().width) * vb.w,
                y: vb.y - (e.movementY / svg.getBoundingClientRect().height) * vb.h,
            }));
            return;
        }
        if (marquee) {
            const p = screenToCanvas(svg, viewBox, e.clientX, e.clientY);
            setMarquee((m) => (m ? { ...m, x1: p.x, y1: p.y } : m));
            return;
        }
        const drag = dragRef.current;
        if (!drag) return;
        const p = screenToCanvas(svg, viewBox, e.clientX, e.clientY);
        if (drag.kind === 'move') {
            const dx = p.x - drag.startCanvas.x;
            const dy = p.y - drag.startCanvas.y;
            setLiveOverrides((prev) => {
                const next = { ...prev };
                for (const [id, start] of Object.entries(drag.elements)) {
                    next[id] = { x: start.x + dx, y: start.y + dy };
                }
                return next;
            });
        } else if (drag.kind === 'rotate' && drag.elementId && drag.startAngle !== undefined) {
            const start = drag.elements[drag.elementId];
            const angle = Math.atan2(p.y - start.y, p.x - start.x) * (180 / Math.PI);
            const rotation = start.rotation + (angle - drag.startAngle);
            setLiveOverrides((prev) => ({ ...prev, [drag.elementId as string]: { rotation } }));
        } else if (drag.kind === 'resize' && drag.elementId && drag.startBBox) {
            const start = drag.elements[drag.elementId];
            const dist = Math.hypot(p.x - start.x, p.y - start.y);
            const startDist = Math.hypot(drag.startBBox.w, drag.startBBox.h) / 2 || 1;
            const ratio = Math.max(0.1, dist / startDist);
            if (start.paramValue !== undefined) {
                // handled fully on commit (regenerates via the param) -- no
                // cheap local preview available without re-running the
                // generator, so just preview via scale in the meantime.
            }
            setLiveOverrides((prev) => ({ ...prev, [drag.elementId as string]: { scale: start.scale * ratio } }));
        }
    };

    const onCanvasPointerUp = () => {
        if (marquee) {
            const x0 = Math.min(marquee.x0, marquee.x1), x1 = Math.max(marquee.x0, marquee.x1);
            const y0 = Math.min(marquee.y0, marquee.y1), y1 = Math.max(marquee.y0, marquee.y1);
            // Hit-test by each element's own center point -- simple and
            // predictable rather than full bbox-intersection, a deliberate
            // v1 scoping choice.
            const hit = topLevel.filter((el) => el.x >= x0 && el.x <= x1 && el.y >= y0 && el.y <= y1);
            if (hit.length) setSelection(new Set(hit.map((el) => el.id)));
            setMarquee(null);
            return;
        }
        const drag = dragRef.current;
        dragRef.current = null;
        if (!drag) return;
        if (drag.kind === 'move') {
            for (const [id, override] of Object.entries(liveOverrides)) {
                const start = drag.elements[id];
                if (!start || override.x === undefined) continue;
                const before = { x: start.x, y: start.y };
                const after = { x: override.x, y: override.y };
                editCanvasElement(id, after);
                pushUndo({
                    undo: () => editCanvasElement(id, before),
                    redo: () => editCanvasElement(id, after),
                });
            }
        } else if (drag.kind === 'rotate' && drag.elementId) {
            const override = liveOverrides[drag.elementId];
            const start = drag.elements[drag.elementId];
            if (override?.rotation !== undefined) {
                const before = { rotation: start.rotation };
                const after = { rotation: override.rotation };
                editCanvasElement(drag.elementId, after);
                pushUndo({ undo: () => editCanvasElement(drag.elementId as string, before),
                            redo: () => editCanvasElement(drag.elementId as string, after) });
            }
        } else if (drag.kind === 'resize' && drag.elementId) {
            const id = drag.elementId;
            const start = drag.elements[id];
            const override = liveOverrides[id];
            const el = topLevel.find((c) => c.id === id);
            const paramName = el ? primarySizeParam(el) : null;
            if (el && paramName && start.paramValue !== undefined && override?.scale !== undefined) {
                const newValue = Math.max(1, start.paramValue * (override.scale / start.scale));
                const before = { params: { [paramName]: start.paramValue } };
                const after = { params: { [paramName]: newValue } };
                editCanvasElement(id, after);
                pushUndo({ undo: () => editCanvasElement(id, before), redo: () => editCanvasElement(id, after) });
            } else if (override?.scale !== undefined) {
                const before = { scale: start.scale };
                const after = { scale: override.scale };
                editCanvasElement(id, after);
                pushUndo({ undo: () => editCanvasElement(id, before), redo: () => editCanvasElement(id, after) });
            }
        }
        setLiveOverrides({});
    };

    // -- delete / group / ungroup -----------------------------------------------

    const deleteSelection = useCallback(() => {
        for (const id of selection) {
            const el = topLevel.find((c) => c.id === id);
            if (!el) continue;
            deleteCanvasElement(id);
            pushUndo({ undo: () => restoreCanvasElement(el), redo: () => deleteCanvasElement(id) });
        }
        clearSelection();
    }, [selection, topLevel, deleteCanvasElement, restoreCanvasElement, pushUndo]);

    const groupSelection = useCallback(() => {
        if (selection.size < 2) return;
        const ids = Array.from(selection);
        groupCanvasElements(ids);
        // The resulting group's id isn't known synchronously (the server
        // assigns it) -- undo/redo for grouping is intentionally left off
        // the stack for v1 rather than guessed at.
        clearSelection();
    }, [selection, groupCanvasElements]);

    const ungroupSelection = useCallback(() => {
        for (const id of selection) {
            const el = topLevel.find((c) => c.id === id);
            if (el?.type === 'group') ungroupCanvasElement(id);
        }
        clearSelection();
    }, [selection, topLevel, ungroupCanvasElement]);

    // Figma's own alignment row (left/center/right/top/middle/bottom), shown
    // in the Design panel once 2+ things are selected. Elements only carry a
    // centroid (x, y), not a stored bbox, so this aligns centroids rather
    // than true bbox edges -- the Figma-equivalent behavior for shapes of
    // equal size, and a reasonable v1 approximation otherwise.
    const alignSelection = useCallback((edge: 'left' | 'center' | 'right' | 'top' | 'middle' | 'bottom') => {
        const els = topLevel.filter((el) => selection.has(el.id));
        if (els.length < 2) return;
        const axis = edge === 'left' || edge === 'center' || edge === 'right' ? 'x' : 'y';
        const values = els.map((el) => el[axis]);
        const target = edge === 'left' || edge === 'top' ? Math.min(...values)
            : edge === 'right' || edge === 'bottom' ? Math.max(...values)
                : values.reduce((a, b) => a + b, 0) / values.length;
        for (const el of els) {
            const before = { [axis]: el[axis] };
            const after = { [axis]: target };
            editCanvasElement(el.id, after);
            pushUndo({ undo: () => editCanvasElement(el.id, before), redo: () => editCanvasElement(el.id, after) });
        }
    }, [selection, topLevel, editCanvasElement, pushUndo]);

    // -- keyboard shortcuts -------------------------------------------------

    useEffect(() => {
        const handler = (e: KeyboardEvent) => {
            const tag = (document.activeElement?.tagName ?? '').toLowerCase();
            if (tag === 'input' || tag === 'textarea') return; // typing in the composer/properties panel
            if ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === 'z') {
                e.preventDefault();
                if (e.shiftKey) redo(); else undo();
            } else if ((e.key === 'Delete' || e.key === 'Backspace') && selection.size) {
                e.preventDefault();
                deleteSelection();
            } else if ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === 'g') {
                e.preventDefault();
                if (e.shiftKey) ungroupSelection(); else groupSelection();
            } else if (!e.ctrlKey && !e.metaKey && e.key.toLowerCase() === 'v') {
                setTool('select'); // Figma's own shortcuts for the two tools this stage has
            } else if (!e.ctrlKey && !e.metaKey && e.key.toLowerCase() === 'h') {
                setTool('hand');
            } else if ((e.ctrlKey || e.metaKey) && e.key === '0') {
                e.preventDefault();
                zoomToFit();
            } else if ((e.ctrlKey || e.metaKey) && (e.key === '=' || e.key === '+')) {
                e.preventDefault();
                zoomBy(1 / 1.2);
            } else if ((e.ctrlKey || e.metaKey) && e.key === '-') {
                e.preventDefault();
                zoomBy(1.2);
            }
        };
        window.addEventListener('keydown', handler);
        return () => window.removeEventListener('keydown', handler);
    }, [undo, redo, selection, deleteSelection, groupSelection, ungroupSelection, zoomToFit, zoomBy]);

    const selectedElements = topLevel.filter((el) => selection.has(el.id)).map(displayElement);
    const sortedForLayers = [...topLevel].sort((a, b) => b.z - a.z);

    const zoomPercent = Math.round((DEFAULT_VIEWBOX.w / viewBox.w) * 100);

    return (
        <main className="flex min-h-0 flex-col border-y border-line-soft">
            <Toolbar
                tool={tool} onToolChange={setTool} zoomPercent={zoomPercent}
                onZoomIn={() => zoomBy(1 / 1.2)} onZoomOut={() => zoomBy(1.2)}
                onZoomReset={() => zoomBy(DEFAULT_VIEWBOX.w / viewBox.w)} onZoomToFit={zoomToFit}
            />
            <div className="flex min-h-0 flex-1 gap-4 pt-3">
                {/* Figma's own split: layers/pages on the LEFT, the
                    design/properties panel on the RIGHT -- not bundled
                    together on one side. */}
                <aside className="w-[13rem] shrink-0 overflow-y-auto noScrollbar">
                    <LayersPanel
                        elements={sortedForLayers}
                        selection={selection}
                        onSelect={selectOnly}
                        onToggle={toggleSelect}
                        onDelete={(id) => {
                            const el = topLevel.find((c) => c.id === id);
                            if (!el) return;
                            deleteCanvasElement(id);
                            pushUndo({ undo: () => restoreCanvasElement(el), redo: () => deleteCanvasElement(id) });
                            setSelection((prev) => { const n = new Set(prev); n.delete(id); return n; });
                        }}
                        onReorder={(id, z) => editCanvasElement(id, { z })}
                    />
                </aside>

                <svg
                    ref={svgRef}
                    className={`min-h-0 flex-1 touch-none select-none border border-line ${tool === 'hand' ? 'cursor-grab' : ''}`}
                    viewBox={`${viewBox.x} ${viewBox.y} ${viewBox.w} ${viewBox.h}`}
                    onPointerDown={onCanvasPointerDown}
                    onPointerMove={onCanvasPointerMove}
                    onPointerUp={onCanvasPointerUp}
                >
                    {/* Figma's real canvas is a plain, flat surface (no dot
                        grid in the Design editor -- that's FigJam), just a
                        tone distinct from the chrome around it. Covers the
                        whole viewBox so it tracks pan/zoom instead of
                        scrolling independently of the artwork. */}
                    <rect
                        x={viewBox.x} y={viewBox.y} width={viewBox.w} height={viewBox.h}
                        fill="var(--color-panel)" pointerEvents="none"
                    />
                    {/* The actual drawing surface's own bounds -- distinct from the SVG
                        viewport border above, which just frames whatever's currently
                        panned/zoomed into view. This stays fixed at the canvas's real
                        origin/size regardless of pan or zoom, so there's always a clear
                        answer to "where is the canvas" even when it's mostly scrolled
                        out of view. */}
                    <rect
                        x={DEFAULT_VIEWBOX.x} y={DEFAULT_VIEWBOX.y} width={DEFAULT_VIEWBOX.w} height={DEFAULT_VIEWBOX.h}
                        fill="none" stroke="var(--color-ink-dim)" strokeWidth={2} pointerEvents="none"
                    />
                    {topLevel.length === 0 && (
                        <text x={0} y={0} textAnchor="middle" className="fill-ink-dim" style={{ fontSize: 14 }}>
                            Ask R.A.V.E.N to draw something.
                        </text>
                    )}
                    {sortedForLayers.slice().reverse().map((raw) => {
                        const el = displayElement(raw);
                        return (
                            <g
                                key={el.id}
                                ref={(node) => { if (node) shapeRefs.current.set(el.id, node); else shapeRefs.current.delete(el.id); }}
                                transform={`translate(${el.x} ${el.y}) rotate(${el.rotation}) scale(${el.scale ?? 1})`}
                                onPointerDown={(e) => onShapePointerDown(e, raw)}
                                className="cursor-move"
                            >
                                <ShapeGeometry el={el} />
                            </g>
                        );
                    })}
                    {selectedElements.map((el) => {
                        const bbox = localBBox(shapeRefs.current.get(el.id) ?? null) ?? { x: -20, y: -20, w: 40, h: 40 };
                        return (
                            <g
                                key={`sel-${el.id}`}
                                transform={`translate(${el.x} ${el.y}) rotate(${el.rotation}) scale(${el.scale ?? 1})`}
                                onPointerDown={(e) => onShapePointerDown(e, topLevel.find((c) => c.id === el.id) as CanvasElement)}
                            >
                                <SelectionChrome bbox={bbox} />
                            </g>
                        );
                    })}
                    {marquee && (
                        <rect
                            x={Math.min(marquee.x0, marquee.x1)} y={Math.min(marquee.y0, marquee.y1)}
                            width={Math.abs(marquee.x1 - marquee.x0)} height={Math.abs(marquee.y1 - marquee.y0)}
                            fill="var(--color-line-soft)" stroke="var(--color-ink)" strokeDasharray="4 3"
                        />
                    )}
                </svg>

                <aside className="w-[15rem] shrink-0 overflow-y-auto noScrollbar">
                    <PropertiesPanel
                        elements={selectedElements}
                        onChange={(id, patch) => editCanvasElement(id, patch)}
                        onGroup={selection.size >= 2 ? groupSelection : undefined}
                        onUngroup={selectedElements.some((e) => e.type === 'group') ? ungroupSelection : undefined}
                        onAlign={selection.size >= 2 ? alignSelection : undefined}
                    />
                </aside>
            </div>

            {statusText != null && busy && <div className="self-start px-1.5 text-[0.82rem] text-ink-dim">{statusText}</div>}
            {error && (
                <div role="alert" className="mx-1.5 flex justify-between gap-4 border border-danger px-3 py-2 text-[0.85rem] text-danger">
                    <span>{error}</span>
                    <button onClick={onDismissError} aria-label="Dismiss error" className="cursor-pointer text-[1.1rem] leading-none">
                        ×
                    </button>
                </div>
            )}

            <Composer
                connected={connected}
                busy={busy}
                cancelling={cancelling}
                blocked={!!pendingConfirm}
                onSend={onSend}
                onCancel={onCancel}
            />
        </main>
    );
};

// ---------------------------------------------------------------------------
// Figma's own top toolbar: a tool switch (Select/Hand -- V/H, the same two
// shortcuts Figma itself uses) on the left, zoom controls on the right.
// Plain text labels, not an icon set -- matching this app's existing
// convention (the sidebar's own "×"/"↑"/"↓" buttons are the only "icons"
// anywhere in raven_ui, no icon font/SVG sprite is used elsewhere).
// ---------------------------------------------------------------------------

function toolButtonClass(active: boolean): string {
    return `cursor-pointer border px-2.5 py-1 text-[0.8rem] ${active
        ? 'border-strong bg-strong text-onstrong'
        : 'border-ink text-ink hover:bg-strong hover:text-onstrong'
        }`;
}

function Toolbar({
    tool, onToolChange, zoomPercent, onZoomIn, onZoomOut, onZoomReset, onZoomToFit,
}: {
    tool: 'select' | 'hand';
    onToolChange: (tool: 'select' | 'hand') => void;
    zoomPercent: number;
    onZoomIn: () => void;
    onZoomOut: () => void;
    onZoomReset: () => void;
    onZoomToFit: () => void;
}) {
    return (
        <div className="flex items-center justify-between border-b border-line-soft px-1.5 py-2">
            <div className="flex gap-1.5">
                <button onClick={() => onToolChange('select')} aria-label="Select tool (V)" title="Select (V)"
                        className={toolButtonClass(tool === 'select')}>
                    Select
                </button>
                <button onClick={() => onToolChange('hand')} aria-label="Hand tool (H)" title="Pan (H)"
                        className={toolButtonClass(tool === 'hand')}>
                    Pan
                </button>
            </div>
            <div className="flex items-center gap-1 text-[0.8rem] text-ink-dim">
                <button onClick={onZoomOut} aria-label="Zoom out" className="cursor-pointer px-2 hover:text-ink">
                    −
                </button>
                <button
                    onClick={onZoomReset} aria-label="Reset zoom to 100%" title="Reset to 100%"
                    className="w-12 cursor-pointer text-center tabular-nums hover:text-ink"
                >
                    {zoomPercent}%
                </button>
                <button onClick={onZoomIn} aria-label="Zoom in" className="cursor-pointer px-2 hover:text-ink">
                    +
                </button>
                <button
                    onClick={onZoomToFit} aria-label="Zoom to fit everything" title="Zoom to fit (Ctrl+0)"
                    className="ml-1 cursor-pointer border border-line px-2 py-0.5 hover:border-ink hover:text-ink"
                >
                    Fit
                </button>
            </div>
        </div>
    );
}

function LayersPanel({
    elements, selection, onSelect, onToggle, onDelete, onReorder,
}: {
    elements: CanvasElement[];
    selection: Set<string>;
    onSelect: (id: string) => void;
    onToggle: (id: string) => void;
    onDelete: (id: string) => void;
    onReorder: (id: string, z: number) => void;
}) {
    const move = (index: number, dir: -1 | 1) => {
        const other = elements[index + dir];
        const current = elements[index];
        if (!other) return;
        onReorder(current.id, other.z);
        onReorder(other.id, current.z);
    };
    return (
        <div>
            <div className="mb-2.5 flex items-center gap-2 text-[0.85rem] text-ink-dim">
                <span className="w-max text-nowrap">Layers</span>
                <div className="h-px w-full bg-ink" />
            </div>
            {elements.length === 0 ? (
                <div className="text-[0.85rem] text-ink-dim">Nothing drawn yet</div>
            ) : (
                <ul className="m-0 flex list-none flex-col gap-0.5 p-0">
                    {elements.map((el, i) => (
                        <li key={el.id} className="group flex items-stretch border-2 border-transparent hover:border-ink">
                            <button
                                onClick={(e) => (e.shiftKey ? onToggle(el.id) : onSelect(el.id))}
                                title={el.id}
                                className={`min-w-0 flex-1 cursor-pointer overflow-hidden border-l-2 px-2 py-1.5 text-left text-[0.8rem] text-ellipsis whitespace-nowrap ${selection.has(el.id) ? 'border-strong bg-strong font-semibold text-onstrong' : 'border-ink'
                                    }`}
                            >
                                {(el.generator ?? el.type).replace(/_/g, ' ')}
                            </button>
                            <button onClick={() => move(i, -1)} disabled={i === 0} aria-label="Move up"
                                    className="hidden cursor-pointer px-1 text-ink-dim hover:text-ink group-hover:block disabled:cursor-not-allowed disabled:opacity-30">
                                ↑
                            </button>
                            <button onClick={() => move(i, 1)} disabled={i === elements.length - 1} aria-label="Move down"
                                    className="hidden cursor-pointer px-1 text-ink-dim hover:text-ink group-hover:block disabled:cursor-not-allowed disabled:opacity-30">
                                ↓
                            </button>
                            <button onClick={() => onDelete(el.id)} aria-label={`Delete ${el.id}`}
                                    className="hidden cursor-pointer px-2 text-ink-dim hover:text-danger group-hover:block">
                                ×
                            </button>
                        </li>
                    ))}
                </ul>
            )}
        </div>
    );
}

const NUMERIC_PARAM_STEP: Record<string, number> = { sides: 1, points: 1 };

type Edge = 'left' | 'center' | 'right' | 'top' | 'middle' | 'bottom';
const ALIGN_BUTTONS: { edge: Edge; label: string }[] = [
    { edge: 'left', label: '⊢' }, { edge: 'center', label: '⊣⊢' }, { edge: 'right', label: '⊣' },
    { edge: 'top', label: '⊤' }, { edge: 'middle', label: '⊤⊥' }, { edge: 'bottom', label: '⊥' },
];

function PropertiesPanel({
    elements, onChange, onGroup, onUngroup, onAlign,
}: {
    elements: CanvasElement[];
    onChange: (id: string, patch: Record<string, unknown>) => void;
    onGroup?: () => void;
    onUngroup?: () => void;
    onAlign?: (edge: Edge) => void;
}) {
    if (elements.length === 0) {
        return (
            <div>
                <div className="mb-2.5 flex items-center gap-2 text-[0.85rem] text-ink-dim">
                    <span className="w-max text-nowrap">Design</span>
                    <div className="h-px w-full bg-ink" />
                </div>
                <div className="text-[0.85rem] text-ink-dim">Select a shape to edit it</div>
            </div>
        );
    }
    const el = elements[0];
    const single = elements.length === 1;
    return (
        <div className="flex flex-col gap-3">
            <div className="mb-1 flex items-center gap-2 text-[0.85rem] text-ink-dim">
                <span className="w-max text-nowrap">Design</span>
                <div className="h-px w-full bg-ink" />
            </div>
            {/* Figma's own "Align" row -- only meaningful with 2+ selected,
                same gating Figma itself uses (it hides the row entirely for
                a single selection rather than disabling it). */}
            {onAlign && (
                <div className="flex gap-1">
                    {ALIGN_BUTTONS.map(({ edge, label }) => (
                        <button
                            key={edge} onClick={() => onAlign(edge)} title={`Align ${edge}`}
                            className="flex-1 cursor-pointer border border-ink py-1 text-[0.78rem] hover:bg-strong hover:text-onstrong"
                        >
                            {label}
                        </button>
                    ))}
                </div>
            )}
            {(onGroup || onUngroup) && (
                <div className="flex gap-2">
                    {onGroup && (
                        <button onClick={onGroup} className="flex-1 cursor-pointer border border-ink px-2 py-1.5 text-[0.78rem] hover:bg-strong hover:text-onstrong">
                            Group
                        </button>
                    )}
                    {onUngroup && (
                        <button onClick={onUngroup} className="flex-1 cursor-pointer border border-ink px-2 py-1.5 text-[0.78rem] hover:bg-strong hover:text-onstrong">
                            Ungroup
                        </button>
                    )}
                </div>
            )}
            {single && (
                <>
                    {/* Position (X/Y) and rotation paired per row, matching
                        Figma's own compact two-up field layout rather than
                        one field per full-width row. */}
                    <div className="flex gap-2">
                        <NumberField label="X" value={el.x} onCommit={(v) => onChange(el.id, { x: v })} />
                        <NumberField label="Y" value={el.y} onCommit={(v) => onChange(el.id, { y: v })} />
                    </div>
                    <NumberField label="Rotation" value={el.rotation} onCommit={(v) => onChange(el.id, { rotation: v })} />
                    {el.type !== 'group' && Object.entries(el.params).map(([key, value]) => (
                        typeof value === 'number' ? (
                            <NumberField
                                key={key} label={key} value={value}
                                step={NUMERIC_PARAM_STEP[key] ?? undefined}
                                onCommit={(v) => onChange(el.id, { params: { [key]: v } })}
                            />
                        ) : null
                    ))}
                    {el.type !== 'group' && (
                        <div className="flex gap-2">
                            <ColorField label="Fill" value={el.fill} onCommit={(v) => onChange(el.id, { fill: v })} />
                            <ColorField label="Stroke" value={el.stroke} onCommit={(v) => onChange(el.id, { stroke: v })} />
                        </div>
                    )}
                </>
            )}
            {!single && <div className="text-[0.8rem] text-ink-dim">{elements.length} shapes selected</div>}
        </div>
    );
}

function NumberField({ label, value, step, onCommit }: { label: string; value: number; step?: number; onCommit: (v: number) => void }) {
    const [text, setText] = useState(String(value));
    useEffect(() => setText(String(value)), [value]);
    const commit = () => {
        const n = Number(text);
        if (!Number.isNaN(n)) onCommit(n);
        else setText(String(value));
    };
    return (
        <label className="flex flex-1 items-center justify-between gap-2 text-[0.8rem]">
            <span className="text-ink-dim">{label}</span>
            <input
                type="number" step={step ?? 'any'} value={text}
                onChange={(e) => setText(e.target.value)}
                onBlur={commit}
                onKeyDown={(e) => { if (e.key === 'Enter') (e.target as HTMLInputElement).blur(); }}
                className="w-16 min-w-0 flex-1 border border-line bg-transparent px-1.5 py-1 text-right outline-none focus:border-ink"
            />
        </label>
    );
}

function ColorField({ label, value, onCommit }: { label: string; value: string; onCommit: (v: string) => void }) {
    const isColor = /^#[0-9a-fA-F]{3,8}$/.test(value);
    return (
        <label className="flex flex-1 items-center justify-between gap-2 text-[0.8rem]">
            <span className="text-ink-dim">{label}</span>
            <input
                type="color" value={isColor ? value : '#000000'}
                onChange={(e) => onCommit(e.target.value)}
                className="h-6 w-10 cursor-pointer border border-line bg-transparent p-0"
            />
        </label>
    );
}

