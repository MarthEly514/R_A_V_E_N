"""Mathematically-generated design elements for the desktop app's Design mode.

Pure math only -- no I/O, no `self`, no server/canvas access (that lives in
Assistant/Store/server.py). Every generator is a `params -> geometry` function:
it returns a dict with a "type", the RENDERED geometry ("points" for a
polygon/star, "d" for an SVG path, or "children" for a group), and the
"params" that produced it. `params` is the only thing ever hand-edited (e.g.
via the design mode's properties panel or update_canvas_element) -- geometry
is always regenerated by calling the same generator again with new params,
never patched directly, so a shape edited later stays mathematically exact
instead of drifting into an approximation of itself.

Convention (stated once, relied on everywhere else -- the renderer, the
rotate handle, update_canvas_element's regeneration step): every element's
geometry is expressed relative to its own LOCAL ORIGIN (0, 0), and rotation
is about that same local origin. `place_element` then supplies the element's
actual canvas position (x, y), rotation, and style -- so a generator never
needs to know where on the canvas it will end up.

A "group" element's children are positioned relative to the GROUP's local
origin, the same rule as any other element's geometry -- so a group is
itself just another element (with x/y/rotation/scale placing the whole
assembly on the canvas), which is what makes `group_elements`/`ungroup_elements`
(Assistant, D-design step) straightforward: grouping existing canvas elements
re-expresses each child's position relative to the new group's origin, and
ungrouping adds the group's own x/y/rotation/scale back onto each child and
throws the wrapper away -- no separate "transform" bookkeeping needed.
"""
import math
import uuid
from typing import Sequence

PHI = (1 + 5 ** 0.5) / 2  # the golden ratio


def new_element_id() -> str:
    return f"el_{uuid.uuid4().hex[:8]}"


def place_element(
    el: dict,
    *,
    x: float = 0.0,
    y: float = 0.0,
    rotation: float = 0.0,
    scale: float = 1.0,
    fill: str = "#141414",
    stroke: str = "none",
    stroke_width: float = 1.0,
    z: int = 0,
    element_id: str | None = None,
) -> dict:
    """Layers the fields every element needs (id, position, style, z-order)
    onto a generator's raw geometry dict -- kept as one shared step so no
    generator duplicates this bookkeeping."""
    el["id"] = element_id or new_element_id()
    el["x"] = x
    el["y"] = y
    el["rotation"] = rotation
    el["scale"] = scale
    el["fill"] = fill
    el["stroke"] = stroke
    el["stroke_width"] = stroke_width
    el["z"] = z
    return el


def _path_from_points(points: Sequence[tuple[float, float]], closed: bool = False) -> str:
    if not points:
        return ""
    d = f"M {points[0][0]:.3f} {points[0][1]:.3f} " + " ".join(
        f"L {px:.3f} {py:.3f}" for px, py in points[1:]
    )
    return d + " Z" if closed else d


def _polygon_vertices(n: int, r: float, start_angle: float = -math.pi / 2) -> list[tuple[float, float]]:
    """n points evenly spaced around a circle of radius r, starting straight
    up by default (a hexagon drawn this way has a flat-looking top vertex,
    matching how most people expect a regular polygon to sit)."""
    return [
        (r * math.cos(start_angle + 2 * math.pi * k / n), r * math.sin(start_angle + 2 * math.pi * k / n))
        for k in range(n)
    ]


# --------------------------------------------------------------------------
# Golden ratio
# --------------------------------------------------------------------------

def golden_rectangle(width: float = 160.0) -> dict:
    """A rectangle whose sides are in the golden ratio (width : height = phi : 1)."""
    height = width / PHI
    points = [(-width / 2, -height / 2), (width / 2, -height / 2),
              (width / 2, height / 2), (-width / 2, height / 2)]
    return {"type": "polygon", "points": points, "params": {"width": width, "height": height}}


def golden_spiral(size: float = 120.0, turns: float = 3.0, samples_per_turn: int = 48) -> dict:
    """A logarithmic spiral that grows by a factor of `phi` every quarter
    turn -- the same curve traced by nesting golden rectangles, approximated
    here as a sampled polyline (an SVG path) rather than literal nested
    rectangle arcs, since a smooth path edits/scales more predictably."""
    b = math.log(PHI) / (math.pi / 2)
    total_theta = max(turns, 0.1) * 2 * math.pi
    n = max(int(samples_per_turn * turns), 8)
    # normalize so the OUTERMOST point sits at radius `size` -- turns/size
    # then behave as independent, predictable params rather than size
    # implicitly depending on how many turns were requested.
    norm = size / math.exp(b * total_theta)
    points = []
    for i in range(n + 1):
        theta = total_theta * i / n
        r = norm * math.exp(b * theta)
        points.append((r * math.cos(theta), r * math.sin(theta)))
    return {"type": "path", "d": _path_from_points(points), "params": {"size": size, "turns": turns}}


# --------------------------------------------------------------------------
# Polygons
# --------------------------------------------------------------------------

def regular_polygon(sides: int = 6, radius: float = 80.0) -> dict:
    sides = max(int(sides), 3)
    points = _polygon_vertices(sides, radius)
    return {"type": "polygon", "points": points, "params": {"sides": sides, "radius": radius}}


def star_polygon(points: int = 5, outer_radius: float = 100.0, inner_radius: float = 40.0) -> dict:
    points = max(int(points), 3)
    verts = []
    for k in range(points * 2):
        r = outer_radius if k % 2 == 0 else inner_radius
        angle = -math.pi / 2 + math.pi * k / points
        verts.append((r * math.cos(angle), r * math.sin(angle)))
    return {
        "type": "star",
        "points": verts,
        "params": {"points": points, "outer_radius": outer_radius, "inner_radius": inner_radius},
    }


# --------------------------------------------------------------------------
# Radial symmetry / mandalas
# --------------------------------------------------------------------------

def radial_pattern(motif: dict, repetitions: int = 6, orbit_radius: float = 0.0,
                    spin_with_orbit: bool = True) -> dict:
    """Repeats `motif` (an already-generated, un-placed element, e.g. the
    dict a call to regular_polygon/star_polygon/golden_rectangle returns)
    `repetitions` times around a shared center -- the mandala/rosette
    primitive. Each copy sits `orbit_radius` from the center, further
    rotated by its own share of the full turn; `spin_with_orbit` additionally
    rotates each copy to face outward (a petal-like layout) rather than all
    copies staying upright."""
    repetitions = max(int(repetitions), 1)
    children = []
    for k in range(repetitions):
        angle_deg = 360.0 * k / repetitions
        angle_rad = math.radians(angle_deg - 90)  # first copy points up, like _polygon_vertices' default
        child = dict(motif)
        child["id"] = new_element_id()
        child["x"] = orbit_radius * math.cos(angle_rad)
        child["y"] = orbit_radius * math.sin(angle_rad)
        child["rotation"] = angle_deg if spin_with_orbit else 0.0
        child["scale"] = 1.0
        child.setdefault("fill", "#141414")
        child.setdefault("stroke", "none")
        child.setdefault("stroke_width", 1.0)
        children.append(child)
    return {
        "type": "group",
        "children": children,
        "params": {
            "repetitions": repetitions, "orbit_radius": orbit_radius, "spin_with_orbit": spin_with_orbit,
            "motif_type": motif.get("type"), "motif_params": motif.get("params", {}),
        },
    }


# --------------------------------------------------------------------------
# Grid / layout systems
# --------------------------------------------------------------------------

def grid_layout(rows: int = 3, cols: int = 3, cell_width: float = 80.0,
                 cell_height: float = 80.0, gutter: float = 12.0) -> dict:
    """A group of empty placeholder rects arranged in a grid, centered on
    the group's own local origin -- a layout aid (columns/rows/baseline),
    not shape content; fill something into each cell yourself if needed."""
    rows, cols = max(int(rows), 1), max(int(cols), 1)
    total_w = cols * cell_width + (cols - 1) * gutter
    total_h = rows * cell_height + (rows - 1) * gutter
    rect_points = [(-cell_width / 2, -cell_height / 2), (cell_width / 2, -cell_height / 2),
                   (cell_width / 2, cell_height / 2), (-cell_width / 2, cell_height / 2)]
    children = []
    for r in range(rows):
        for c in range(cols):
            cx = -total_w / 2 + c * (cell_width + gutter) + cell_width / 2
            cy = -total_h / 2 + r * (cell_height + gutter) + cell_height / 2
            children.append({
                "id": new_element_id(), "type": "polygon", "x": cx, "y": cy,
                "rotation": 0.0, "scale": 1.0, "fill": "none", "stroke": "#8a8a8a",
                "stroke_width": 1.0, "points": rect_points,
                "params": {"width": cell_width, "height": cell_height},
            })
    return {
        "type": "group", "children": children,
        "params": {"rows": rows, "cols": cols, "cell_width": cell_width,
                   "cell_height": cell_height, "gutter": gutter},
    }


# --------------------------------------------------------------------------
# Parametric curves
# --------------------------------------------------------------------------

def bezier_curve(control_points: Sequence[Sequence[float]]) -> dict:
    """A single Bezier segment: 2 points is a straight line, 3 is quadratic,
    4 is cubic. Coordinates are re-centered on the control points' own
    bounding-box center, so the returned element's local origin sits in the
    middle of the curve like every other generator's geometry does."""
    pts = [(float(p[0]), float(p[1])) for p in control_points]
    if len(pts) < 2:
        raise ValueError("bezier_curve needs at least 2 control points")
    cx = (min(p[0] for p in pts) + max(p[0] for p in pts)) / 2
    cy = (min(p[1] for p in pts) + max(p[1] for p in pts)) / 2
    local = [(px - cx, py - cy) for px, py in pts]
    if len(local) == 2:
        d = f"M {local[0][0]:.3f} {local[0][1]:.3f} L {local[1][0]:.3f} {local[1][1]:.3f}"
    elif len(local) == 3:
        d = (f"M {local[0][0]:.3f} {local[0][1]:.3f} "
             f"Q {local[1][0]:.3f} {local[1][1]:.3f} {local[2][0]:.3f} {local[2][1]:.3f}")
    else:
        local = local[:4]
        d = (f"M {local[0][0]:.3f} {local[0][1]:.3f} "
             f"C {local[1][0]:.3f} {local[1][1]:.3f} {local[2][0]:.3f} {local[2][1]:.3f} "
             f"{local[3][0]:.3f} {local[3][1]:.3f}")
    return {"type": "path", "d": d, "params": {"control_points": [list(p) for p in pts]}}


def lissajous_curve(a: float = 3.0, b: float = 2.0, delta: float = math.pi / 2,
                     amplitude: float = 100.0, samples: int = 200) -> dict:
    """The Lissajous figure x = A sin(a t + delta), y = A sin(b t), sampled
    over one full period and closed into a loop -- integer a:b ratios give
    the classic closed decorative curves."""
    samples = max(int(samples), 16)
    points = []
    for i in range(samples):
        t = 2 * math.pi * i / samples
        points.append((amplitude * math.sin(a * t + delta), amplitude * math.sin(b * t)))
    return {
        "type": "path", "d": _path_from_points(points, closed=True),
        "params": {"a": a, "b": b, "delta": delta, "amplitude": amplitude, "samples": samples},
    }


GENERATORS = {
    "golden_rectangle": golden_rectangle,
    "golden_spiral": golden_spiral,
    "regular_polygon": regular_polygon,
    "star_polygon": star_polygon,
    "grid_layout": grid_layout,
    "bezier_curve": bezier_curve,
    "lissajous_curve": lissajous_curve,
}


def regenerate(element_type_key: str, params: dict) -> dict:
    """Re-run the generator that made an element, with (possibly edited)
    params -- the mechanism behind "editing params regenerates geometry
    exactly, never drifts." `element_type_key` is the generator's own name
    (stored as an element's "generator" field by tools.py), not its
    "type" (several generators can share a rendered "type", e.g. every
    polygon-like shape)."""
    fn = GENERATORS.get(element_type_key)
    if fn is None:
        raise ValueError(f"Unknown generator: {element_type_key}")
    return fn(**params)
